/**
 * Returns audio frequencies for all played strings in a chord shape
 */
export function getChordFrequencies(chord: ChordShape): number[] {
  const freqs: number[] = [];
  // frets is [string6, string5, string4, string3, string2, string1]
  chord.frets.forEach((fret, index) => {
    if (fret !== -1) {
      // STANDARD_TUNING is ordered from 1 (high E) to 6 (low E)
      // So string6 corresponds to STANDARD_TUNING[5], string5 to [4], etc.
      const stringDef = STANDARD_TUNING[5 - index];
      const fretNote = getFretNote(stringDef, fret);
      freqs.push(fretNote.frequencyHz);
    }
  });
  return freqs;
}
